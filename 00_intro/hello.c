/*
 * 00_intro/hello.c
 * --------------------------------------------------------------------------
 * 第 0 章で扱うコンパイルパイプラインの題材。
 *   gcc -E  → プリプロセス (#include 展開、 マクロ展開)   → .i
 *   gcc -S  → コンパイル   (.i → アセンブリ)              → .s
 *   gcc -c  → アセンブル   (.s → ELF .o オブジェクト)     → .o
 *   gcc     → リンク       (.o + libc など → 実行可能)    → 実行ファイル
 *
 * このファイル自身は超シンプル。 何が起きているかを段階的に止めて見る。
 */

/* #include <stdio.h>:
     標準入出力ヘッダ。 ファイル/プロセスの読み書き関数群がまとまっている。
     <...> はシステムインクルードパス検索、 "..." はカレントディレクトリ優先。
     プリプロセス段で この行はヘッダの中身に丸ごと差し替えられる。 */
#include <stdio.h>

/* int main(void):
     C プログラムのエントリポイント。 ホスト環境 (= OS が起動する) では
     int main(void) または int main(int argc, char **argv) が C 規格上の正式形。
     void は「引数を取らない」 を明示する書き方。 () だけだと「引数情報なし」
     と解釈され、 古い C 規格の挙動になるため避ける。 */
int main(void) {
    /* puts(s):
         文字列 s を stdout に出力し、 末尾に改行を 1 つ追加する標準関数。
         戻り値は成功時 非負、 失敗時 EOF。 今回は戻り値を使わない。 */
    puts("hello, deepdive");

    /* main の return 値は **プロセスの終了コード**。 0 は成功、 非 0 は失敗。
       シェルでは $? で取れる。 main を return 文無しで終わらせると C99 以降は
       自動で 0 を返すが、 明示するのが伝統的に推奨される。 */
    return 0;
}
